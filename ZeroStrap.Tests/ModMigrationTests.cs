using System;
using System.Collections.Generic;
using System.IO;
using System.IO.Compression;
using System.Linq;
using System.Text;

using Xunit;

using ZeroStrap.Mods;

namespace ZeroStrap.Tests
{
    public sealed class ModMigrationTests : IDisposable
    {
        private readonly ModStudioFixture _fx = new();

        public void Dispose() => _fx.Dispose();

        private static readonly string[] LooseMods =
        {
            @"content\sounds\ouch.ogg",
            @"content\textures\sky\x.png",
            @"ExtraContent\textures\y.png"
        };

        private void BuildLegacyFixture()
        {
            _fx.WriteMod(@"ClientSettings\ClientAppSettings.json", "{\"DFIntTaskSchedulerTargetFps\":144}");
            _fx.WriteMod(ModStudioFixture.CursorPath, ModStudioFixture.CursorBytes);        // preset resource
            _fx.WriteMod(ModStudioFixture.EmojiPath, ModStudioFixture.EmojiBytes);          // known emoji hash
            _fx.WriteMod(@"content\fonts\CustomFont.ttf", "custom font bytes");             // custom font preset
            _fx.WriteMod(@"content\fonts\families\Arial.json", "{\"name\":\"Arial\"}");     // regenerated by the bootstrapper
            _fx.WriteMod("README.txt", "readme");
            _fx.WriteMod(@"content\textures\a.lock", "lock");
            foreach (string loose in LooseMods)
                _fx.WriteMod(loose, "loose:" + loose);
            _fx.WriteMod(@"random\thing.txt", "outside the allowed folders");               // unmanageable, stays put
            _fx.WriteMod(@"content\scripts\evil.lua", "blocked type");                       // unmanageable, stays put
        }

        [Fact]
        public void MigratesLooseModsWithAVerifiedBackupAndChangesNothingElse()
        {
            BuildLegacyFixture();
            var before = _fx.Snapshot(_fx.Modifications);

            var result = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.Migrated, result.Status);

            // originals are untouched
            var after = _fx.Snapshot(_fx.Modifications);
            Assert.Equal(before.Keys.OrderBy(k => k), after.Keys.OrderBy(k => k));
            foreach (var (path, bytes) in before)
                Assert.Equal(bytes, after[path]);

            // backup holds everything except ClientSettings and *.lock
            Assert.NotNull(result.BackupPath);
            Assert.True(File.Exists(result.BackupPath));
            using (var zip = ZipFile.OpenRead(result.BackupPath!))
            {
                var names = zip.Entries.Select(e => e.FullName).OrderBy(n => n, StringComparer.Ordinal).ToArray();
                var expected = before.Keys
                    .Where(k => !k.StartsWith("ClientSettings\\", StringComparison.OrdinalIgnoreCase) && !k.EndsWith(".lock"))
                    .Select(k => k.Replace('\\', '/'))
                    .OrderBy(n => n, StringComparer.Ordinal)
                    .ToArray();

                Assert.Equal(expected, names);

                using var reader = new StreamReader(zip.GetEntry("content/sounds/ouch.ogg")!.Open());
                Assert.Equal("loose:" + LooseMods[0], reader.ReadToEnd());
            }

            // the legacy package contains exactly the loose mods
            var package = Assert.Single(_fx.Studio.Packages.List());
            Assert.Equal(ModSource.Legacy, package.Manifest.Source);
            Assert.Equal("My existing mods", package.Manifest.Name);
            Assert.Equal(LooseMods.OrderBy(p => p, StringComparer.OrdinalIgnoreCase), package.Files.Select(f => f.RelativePath));
            Assert.Equal("loose:" + LooseMods[1], File.ReadAllText(package.FullPathOf(LooseMods[1])));

            // classification
            Assert.Contains(@"content\fonts\CustomFont.ttf", result.PresetFiles);
            Assert.Contains(@"content\fonts\families\Arial.json", result.PresetFiles);
            Assert.Contains(ModStudioFixture.EmojiPath, result.PresetFiles);
            Assert.Contains(ModStudioFixture.CursorPath, result.PresetFiles);
            Assert.Contains(@"random\thing.txt", result.UnmanagedFiles);
            Assert.Contains(@"content\scripts\evil.lua", result.UnmanagedFiles);
            Assert.Contains("README.txt", result.SkippedFiles);

            // state and ownership
            var state = _fx.Studio.LoadState();
            Assert.True(state.Migrated);
            Assert.Equal(result.BackupPath, state.MigrationBackup);
            Assert.Equal(new[] { package.Id }, state.Enabled);
            var index = _fx.Studio.IndexStore.Load();
            Assert.Equal(3, index.Files.Count);
            Assert.All(index.Files.Values, e => Assert.Equal(package.Id, e.Owner));

            // the first overlay build is a no-op
            var rebuilt = _fx.Studio.Rebuild();
            Assert.True(rebuilt.Plan.IsNoOp);
            Assert.Equal(0, rebuilt.Result.Copied + rebuilt.Result.Deleted + rebuilt.Result.Displaced);
            Assert.Empty(rebuilt.Result.Blocked);

            var afterRebuild = _fx.Snapshot(_fx.Modifications);
            foreach (var (path, bytes) in before)
                Assert.Equal(bytes, afterRebuild[path]);
        }

        [Fact]
        public void LegacyPackageCanBeDisabledAndRestoredWithoutLoss()
        {
            BuildLegacyFixture();
            _fx.Studio.EnsureMigrated();
            string id = _fx.Studio.Packages.List().Single().Id;

            _fx.Studio.SetEnabled(id, false);
            _fx.Studio.Rebuild();

            Assert.False(_fx.ModExists(LooseMods[0]));
            Assert.True(_fx.ModExists(@"random\thing.txt"));
            Assert.True(_fx.ModExists(@"content\fonts\CustomFont.ttf"));
            Assert.True(_fx.ModExists(@"ClientSettings\ClientAppSettings.json"));

            _fx.Studio.SetEnabled(id, true);
            _fx.Studio.Rebuild();

            Assert.Equal("loose:" + LooseMods[0], _fx.ReadMod(LooseMods[0]));
        }

        [Fact]
        public void MigrationRunsOnlyOnce()
        {
            BuildLegacyFixture();
            _fx.Studio.EnsureMigrated();
            _fx.WriteMod(@"content\sounds\added-later.ogg", "later");

            var second = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.AlreadyDone, second.Status);
            Assert.Single(_fx.Studio.Packages.List());
            Assert.Single(Directory.GetFiles(Path.Combine(_fx.StudioDir, "Backups"), "pre-migration-*.zip"));
        }

        [Fact]
        public void BackupFailureAbortsWithoutChangingAnything()
        {
            BuildLegacyFixture();
            var before = _fx.Snapshot(_fx.Modifications);

            _fx.Studio.Migrator.BackupFault = rel =>
            {
                if (rel.EndsWith("x.png", StringComparison.OrdinalIgnoreCase))
                    throw new IOException("disk full");
            };

            var result = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.Aborted, result.Status);
            Assert.Contains("backup", result.Reason);

            var after = _fx.Snapshot(_fx.Modifications);
            Assert.Equal(before.Keys.OrderBy(k => k), after.Keys.OrderBy(k => k));
            foreach (var (path, bytes) in before)
                Assert.Equal(bytes, after[path]);

            Assert.Empty(_fx.Studio.Packages.List());
            Assert.False(_fx.Studio.LoadState().Migrated);
            Assert.False(File.Exists(_fx.Studio.StateStore.FilePath));
            Assert.False(File.Exists(_fx.Studio.IndexStore.FilePath));

            string backups = Path.Combine(_fx.StudioDir, "Backups");
            Assert.Empty(Directory.Exists(backups) ? Directory.GetFiles(backups) : Array.Empty<string>());

            // the next run retries and succeeds
            _fx.Studio.Migrator.BackupFault = null;
            Assert.Equal(MigrationStatus.Migrated, _fx.Studio.EnsureMigrated().Status);
        }

        [Fact]
        public void NoCandidatesJustMarksMigrated()
        {
            _fx.WriteMod(@"ClientSettings\ClientAppSettings.json", "{}");
            _fx.WriteMod(ModStudioFixture.CursorPath, ModStudioFixture.CursorBytes);
            _fx.WriteMod(@"content\fonts\CustomFont.ttf", "font");
            _fx.WriteMod("README.txt", "readme");

            var result = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.NoCandidates, result.Status);
            Assert.True(_fx.Studio.LoadState().Migrated);
            Assert.Empty(_fx.Studio.Packages.List());
            Assert.False(Directory.Exists(Path.Combine(_fx.StudioDir, "Backups")));
            Assert.True(_fx.ModExists(ModStudioFixture.CursorPath));
        }

        [Fact]
        public void MissingModificationsFolderIsFine()
        {
            Directory.Delete(_fx.Modifications, true);

            Assert.Equal(MigrationStatus.NoCandidates, _fx.Studio.EnsureMigrated().Status);
            Assert.True(_fx.Studio.LoadState().Migrated);
        }

        [Fact]
        public void FilesAlreadyOwnedByTheStudioAreNotPackagedAgain()
        {
            BuildLegacyFixture();
            _fx.Studio.EnsureMigrated();

            // simulate an interrupted run: Migrated was never saved, but the index and package exist
            var state = _fx.Studio.LoadState();
            state.Migrated = false;
            state.Enabled.Clear();
            state.Priority.Clear();
            _fx.Studio.StateStore.Save(state);

            var again = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.NoCandidates, again.Status);
            var package = Assert.Single(_fx.Studio.Packages.List());
            var healed = _fx.Studio.LoadState();
            Assert.True(healed.Migrated);
            Assert.Contains(package.Id, healed.Enabled);
        }

        [Fact]
        public void CustomPresetFileWithDifferentContentBecomesALegacyMod()
        {
            // a hand-made cursor (hash differs from the preset's resource) is a mod, not a preset
            _fx.WriteMod(ModStudioFixture.CursorPath, "my own cursor");

            var result = _fx.Studio.EnsureMigrated();

            Assert.Equal(MigrationStatus.Migrated, result.Status);
            Assert.Equal(new[] { ModStudioFixture.CursorPath }, result.PackagedFiles);
            Assert.Empty(_fx.Catalog.GetActive());
        }

        [Fact]
        public void CatalogReportsActivePresetsAndSwitchesThemOffSafely()
        {
            _fx.WriteMod(ModStudioFixture.CursorPath, ModStudioFixture.CursorBytes);
            _fx.WriteMod(@"content\textures\Cursors\KeyboardMouse\ArrowFarCursor.png", "user-made far cursor"); // not preset content
            _fx.WriteMod(@"content\fonts\CustomFont.ttf", "font");

            var active = _fx.Catalog.GetActive();

            Assert.Equal(new[] { "builtin:cursors", "builtin:custom-font" }, active.Select(a => a.Preset.Id).OrderBy(i => i).ToArray());
            Assert.Equal(new[] { ModStudioFixture.CursorPath }, active.Single(a => a.Preset.Id == "builtin:cursors").OwnedPaths);

            int deleted = _fx.Catalog.DisableNow("builtin:cursors");

            Assert.Equal(1, deleted);
            Assert.False(_fx.ModExists(ModStudioFixture.CursorPath));
            Assert.True(_fx.ModExists(@"content\textures\Cursors\KeyboardMouse\ArrowFarCursor.png")); // not the preset's file: kept
            Assert.True(_fx.ModExists(@"content\fonts\CustomFont.ttf"));

            var cursors = _fx.Catalog.Find("builtin:cursors")!;
            Assert.Equal("CursorType", cursors.TaskName);
            Assert.Equal(PresetOffValue.EnumDefault, cursors.OffValue);
            Assert.Equal(5, _fx.Catalog.Presets.Count);
        }
    }
}
